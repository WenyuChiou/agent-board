// How scripts/build-board.ts lays the board bundle out as modules, as pure functions on text, so a test can
// run them on synthetic input without Bun. Claude Code refuses to import a hooks module over 1 MiB on disk
// (line endings included), so the bundle is kept in parts and hooks/board-script.ts imports them (#582).
// Lives beside bundle-text.mjs, which reads what this writes; only that reader is published in the npm package.
import { BUNDLE_ENTRY, isBundleFile } from './bundle-text.mjs'

// Claude Code's limit; the build stops at MAX_MODULE so a CRLF checkout (each LF becomes two bytes) and growth
// between two builds still fit, and it asks for a new split point from SOFT_MODULE on, well before the stop.
export const CLAUDE_LIMIT = 1_048_576
export const MAX_MODULE = 1_000_000
export const SOFT_MODULE = 900_000

const count = number => number.toLocaleString('en-US')
const partPath = number => `hooks/board-script-${number}.ts`

// Splits at the lines that equal `partStarts`. Fixed points, not packed by size: packing would move whole
// modules between files whenever the bundle grows, and pull requests would conflict on them.
export const splitBundle = (code, partStarts) => {
  const lines = code.split('\n')
  const cuts = partStarts.map(start => {
    const first = lines.indexOf(start)
    if (first === -1 || lines.indexOf(start, first + 1) !== -1) {
      throw new Error(`split point "${start}" is not a line of the bundle (or appears twice): pick another module banner for PART_STARTS in scripts/build-board.ts`)
    }
    return first
  })
  cuts.forEach((cut, index) => {
    if (cut === 0) throw new Error(`split point "${partStarts[index]}" is the first line of the bundle, which would leave part 1 empty: pick another module banner for PART_STARTS in scripts/build-board.ts`)
    if (index > 0 && cut <= cuts[index - 1]) throw new Error(`split points are out of order: "${partStarts[index]}" comes before "${partStarts[index - 1]}" in the bundle; list PART_STARTS in scripts/build-board.ts in bundle order`)
  })
  const bounds = [0, ...cuts, lines.length]
  const parts = bounds.slice(0, -1).map((from, index) => lines.slice(from, bounds[index + 1]))
  // The parts must put the same text back together, whatever the split points were.
  if (parts.flat().join('\n') !== code) throw new Error('the bundle parts do not join back to the bundle')
  return parts
}

// Every generated module, by its path in the repository.
export const bundleModules = (code, partStarts) => {
  const parts = splitBundle(code, partStarts)
  const imports = parts.map((_, index) => `import { LINES as PART_${index + 1} } from './board-script-${index + 1}.ts'`)
  const modules = {
    [BUNDLE_ENTRY]: [
      '// Generated by scripts/build-board.ts from scripts/board-cli.ts; do not edit by hand.',
      "// Kept in parts so each module stays under Claude Code's 1 MiB module limit (#582).",
      ...imports,
      `export const BOARD_SCRIPT = [${parts.map((_, index) => `...PART_${index + 1}`).join(', ')}].join('\\n')`,
      '',
    ].join('\n'),
  }
  parts.forEach((lines, index) => {
    modules[partPath(index + 1)] = `// Generated by scripts/build-board.ts: part ${index + 1} of the board bundle; do not edit by hand.\nexport const LINES = [\n${lines.map(line => JSON.stringify(line)).join(',\n')}\n]\n`
  })
  return modules
}

// What the module weighs on a CRLF checkout, the largest it gets on disk: its bytes plus one for each LF.
export const crlfSize = text => Buffer.byteLength(text) + (text.match(/\n/g)?.length ?? 0)

// `files` maps a path to the text that will be written there. Returns each file's sizes, the problems
// that stop the build and the notes that only ask for attention.
export const moduleBudget = files => {
  const sizes = Object.entries(files).map(([path, text]) => ({ path, lf: Buffer.byteLength(text), crlf: crlfSize(text) }))
  const problems = []
  const notes = []
  for (const { path, crlf } of sizes) {
    if (crlf > MAX_MODULE) {
      problems.push(`${path} would be ${count(crlf)} bytes (with CRLF line endings); Claude Code does not load a plugin module over ${count(CLAUDE_LIMIT)} bytes, and this build stops at ${count(MAX_MODULE)}. Add a split point: put a module banner line near the middle of that part (for example "// hooks/serve.ts") in PART_STARTS in scripts/build-board.ts, rebuild, and list the new part in package.json "files".`)
    } else if (crlf > SOFT_MODULE) {
      notes.push(`${path} is ${count(crlf)} of ${count(MAX_MODULE)} bytes; add a split point soon`)
    }
  }
  return { sizes, problems, notes }
}

// The generated files that exist on disk but that the build no longer produces, from the names in hooks/.
export const staleParts = (hookFiles, modules) =>
  hookFiles.map(name => `hooks/${name}`).filter(path => isBundleFile(path) && !(path in modules)).sort()

// The paths a package must list for the installed command to read the bundle, and the ones that are missing.
export const packagedBundleFiles = modules => [...Object.keys(modules), 'scripts/bundle-text.mjs']
export const missingFromPackage = (modules, listed) => packagedBundleFiles(modules).filter(path => !listed.includes(path))
