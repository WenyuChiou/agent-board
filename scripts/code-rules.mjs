import { spawnSync } from 'node:child_process'
import { existsSync, readFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { BUNDLE_ENTRY, bundleParts, isBundleFile } from './bundle-text.mjs'
import { addedLines } from './pr-check.mjs'

// Grep-level rules over the lines a pull request adds (#1546). A correction that used to be a bullet in team-process
// becomes a rule here: add an object to `rules`, with the error that names its cause and the fix, and a failing and a
// passing case in tests/code-rules.test.mjs. Only added lines are read, so a line already on main never blocks.
//
// The lists the rules use are data in scripts/code-rules.json, read from the pull request's checkout (`--repo-dir`),
// so a pull request can add its own entry in the same change. The checker itself still comes from the base branch:
// nothing the pull request wrote is imported or run, only that JSON is read.

const here = dirname(fileURLToPath(import.meta.url))
const REPO_DIR = Symbol.for('agent-board.code-rules.repoDir')
export const CONFIG_PATH = 'scripts/code-rules.json'

// The pull request's list, or this checker's own when the checkout has none because its branch was cut before the file
// existed. When `refs` names the base and head and the merge base already had the list, the pull request removed it:
// that stops the check instead of falling back, so a deleted list never passes (round 2 of #1551).
export const loadConfig = (repoDir = process.cwd(), refs) => {
  const root = resolve(repoDir)
  const own = join(root, CONFIG_PATH)
  if (!existsSync(own) && refs) {
    const { base = 'origin/main', head = 'HEAD', run = spawnSync } = refs
    const mergeBase = run('git', ['merge-base', base, head], { cwd: root, encoding: 'utf8' })
    if (mergeBase.error || mergeBase.status !== 0) throw new Error(`code-rules: ${CONFIG_PATH} is missing and git could not find the merge base of ${base} and ${head}; fetch the base and run again.`)
    // ls-tree prints the path when the merge base has it and nothing when not; any failure stops the check (codex_448).
    const had = run('git', ['ls-tree', '--name-only', mergeBase.stdout.trim(), '--', CONFIG_PATH], { cwd: root, encoding: 'utf8' })
    if (had.error || had.status !== 0) throw new Error(`code-rules: ${CONFIG_PATH} is missing and git could not read the merge base; fetch the base and run again.`)
    if (had.stdout.trim()) throw new Error(`code-rules: this pull request removes ${CONFIG_PATH}; restore it from main (the check reads its list from the pull request).`)
  }
  const path = existsSync(own) ? own : join(here, 'code-rules.json')
  let config
  try { config = JSON.parse(readFileSync(path, 'utf8')) } catch { throw new Error(`code-rules: ${CONFIG_PATH} is not readable JSON; fix it or restore it from main.`) }
  if (!Array.isArray(config?.setTimeoutFiles) || config.setTimeoutFiles.some(item => typeof item !== 'string')) {
    throw new Error(`code-rules: ${CONFIG_PATH} must be {"setTimeoutFiles": ["hooks/..."]}; fix it or restore it from main.`)
  }
  Object.defineProperty(config, REPO_DIR, { value: root, enumerable: false })
  return config
}

const ENTRY_HEADER = '// Generated by scripts/build-board.ts from scripts/board-cli.ts; do not edit by hand.'
const partHeader = number => `// Generated by scripts/build-board.ts: part ${number} of the board bundle; do not edit by hand.`
const startsWithLine = (text, expected) => text === expected || text.startsWith(`${expected}\n`) || text.startsWith(`${expected}\r\n`)

// Only the bundles scripts/build-board.ts writes are exempt: hooks/board-script.ts with its generated entry header,
// and each hooks/board-script-N.ts part that entry imports and that carries both its part header and LINES array (#1563).
const isGeneratedBundle = (path, readFile) => {
  if (!isBundleFile(path)) return false
  const entry = readFile(BUNDLE_ENTRY)
  if (typeof entry !== 'string' || !startsWithLine(entry, ENTRY_HEADER)) return false
  if (path === BUNDLE_ENTRY) return true
  const match = path.match(/^hooks\/board-script-(\d+)\.ts$/)
  if (!match || !bundleParts(entry).includes(path)) return false
  const part = readFile(path)
  if (typeof part !== 'string' || !startsWithLine(part, partHeader(match[1]))) return false
  const nl = part.indexOf('\n')
  if (nl === -1) return false
  return startsWithLine(part.slice(nl + 1), 'export const LINES = [')
}

const REGEX_KEYWORDS = new Set(['return', 'throw', 'case', 'default', 'delete', 'void', 'typeof', 'yield', 'await', 'in', 'instanceof', 'new', 'of', 'else', 'do', 'export', 'extends'])
const COND_KEYWORDS = new Set(['if', 'while', 'for', 'with'])
const REGEX_PREFIX_CHARS = new Set(['(', '[', '{', '}', ',', ';', ':', '?', '!', '~', '=', '+', '-', '*', '/', '%', '&', '|', '^', '<', '>', '${'])

// Scans JS/TS source from its top so each line knows whether it begins inside a comment, string, regex or template
// literal, leaving non-code text out (replaced with spaces) while keeping code inside `${...}` expressions (#1561).
export const codeLinesOf = source => {
  const stack = [{ kind: 'code', braceDepth: 0 }]
  const parenKinds = []
  const lines = []
  let buf = ''
  let lastToken = null
  let prevToken = null
  let lastParenKind = 'other'
  const pushToken = token => { prevToken = lastToken; lastToken = token }
  const canStartRegex = () => {
    if (lastToken === null || lastToken === '${') return true
    if (lastToken === ')') return lastParenKind === 'cond'
    if (lastToken === '++' || lastToken === '--') return false
    if (REGEX_KEYWORDS.has(lastToken) && prevToken !== '.' && prevToken !== '?.') return true
    return REGEX_PREFIX_CHARS.has(lastToken) || REGEX_PREFIX_CHARS.has(lastToken.slice(-1))
  }
  const handleEscape = index => {
    if (source[index + 1] === '\r' && source[index + 2] === '\n') { lines.push(buf); buf = ''; return index + 3 }
    if (source[index + 1] === '\n') { lines.push(buf); buf = ''; return index + 2 }
    if (index + 1 < source.length) { buf += '  '; return index + 2 }
    return index + 1
  }
  let i = 0
  const n = source.length
  while (i < n) {
    const top = stack[stack.length - 1]
    const ch = source[i]
    if (top.kind === 'block-comment') {
      if (ch === '*' && source[i + 1] === '/') { stack.pop(); buf += '  '; i += 2; continue }
      if (ch === '\n') { lines.push(buf); buf = ''; i += 1; continue }
      if (ch !== '\r') buf += ' '
      i += 1
      continue
    }
    if (top.kind === 'string') {
      if (ch === '\\') { i = handleEscape(i); continue }
      if (ch === top.quote) { stack.pop(); buf += ' '; i += 1; pushToken('<str>'); continue }
      if (ch === '\n') { stack.pop(); lines.push(buf); buf = ''; i += 1; pushToken('<str>'); continue }
      if (ch !== '\r') buf += ' '
      i += 1
      continue
    }
    if (top.kind === 'template') {
      if (ch === '\\') { i = handleEscape(i); continue }
      if (ch === '`') { stack.pop(); buf += ' '; i += 1; pushToken('<str>'); continue }
      if (ch === '$' && source[i + 1] === '{') { stack.push({ kind: 'expr', braceDepth: 0 }); buf += '  '; i += 2; pushToken('${'); continue }
      if (ch === '\n') { lines.push(buf); buf = ''; i += 1; continue }
      if (ch !== '\r') buf += ' '
      i += 1
      continue
    }
    if (ch === '\n') { lines.push(buf); buf = ''; i += 1; continue }
    if (ch === ' ' || ch === '\t' || ch === '\r') { if (ch !== '\r') buf += ch; i += 1; continue }
    if (ch === '/' && source[i + 1] === '/') {
      while (i < n && source[i] !== '\n') { if (source[i] !== '\r') buf += ' '; i += 1 }
      continue
    }
    if (ch === '/' && source[i + 1] === '*') { stack.push({ kind: 'block-comment' }); buf += '  '; i += 2; continue }
    if (ch === '/' && canStartRegex()) {
      let j = i + 1
      let inClass = false
      let closed = false
      while (j < n && source[j] !== '\n' && source[j] !== '\r') {
        const rc = source[j]
        if (rc === '\\') { j += 2; continue }
        if (rc === '[' && !inClass) inClass = true
        else if (rc === ']' && inClass) inClass = false
        else if (rc === '/' && !inClass) { closed = true; j += 1; break }
        j += 1
      }
      if (closed) {
        while (j < n && /[a-z]/i.test(source[j])) j += 1
        buf += ' '.repeat(j - i)
        i = j
        pushToken('<regex>')
        continue
      }
    }
    if (ch === "'" || ch === '"') { stack.push({ kind: 'string', quote: ch }); buf += ' '; i += 1; continue }
    if (ch === '`') { stack.push({ kind: 'template' }); buf += ' '; i += 1; continue }
    if (ch === '{') { if (top.kind === 'expr') top.braceDepth += 1; buf += '{'; pushToken('{'); i += 1; continue }
    if (ch === '}') {
      if (top.kind === 'expr') {
        if (top.braceDepth > 0) { top.braceDepth -= 1; buf += '}'; pushToken('}'); i += 1; continue }
        stack.pop(); buf += ' '; pushToken('}'); i += 1; continue
      }
      buf += '}'; pushToken('}'); i += 1; continue
    }
    if (ch === '(') {
      parenKinds.push(COND_KEYWORDS.has(lastToken) && prevToken !== '.' && prevToken !== '?.' ? 'cond' : 'other')
      buf += '('; pushToken('('); i += 1; continue
    }
    if (ch === ')') { lastParenKind = parenKinds.pop() ?? 'other'; buf += ')'; pushToken(')'); i += 1; continue }
    if (/[A-Za-z_$]/.test(ch)) {
      let j = i + 1
      while (j < n && /[A-Za-z0-9_$]/.test(source[j])) j += 1
      const word = source.slice(i, j)
      buf += word; pushToken(word); i = j; continue
    }
    if (/\d/.test(ch)) {
      let j = i + 1
      while (j < n && /[A-Za-z0-9_.]/.test(source[j])) j += 1
      buf += source.slice(i, j); pushToken('<num>'); i = j; continue
    }
    const two = source.slice(i, i + 2)
    if (two === '++' || two === '--' || two === '=>' || two === '?.') { buf += two; pushToken(two); i += 2; continue }
    buf += ch; pushToken(ch); i += 1
  }
  lines.push(buf)
  return lines
}

export const rules = [
  {
    id: 'set-timeout-in-hooks',
    applies: (path, config, readFile = () => undefined) => /^hooks\/.+\.tsx?$/.test(path) && !isGeneratedBundle(path, readFile) && !config.setTimeoutFiles.includes(path),
    test: text => /\bsetTimeout\b/.test(text),
    cause: 'a new `setTimeout` (a call, or the function passed on) in a hooks/ file that is not on the list of files that already use one: a timer in a hook keeps the hook process alive after its work is done or fires after the agent moved on.',
    fix: `start the timer from a file already on the list, or add this file to "setTimeoutFiles" in ${CONFIG_PATH} in the same pull request and say why in its body (the check reads the list from the pull request). For a renamed or moved file, move its path in that list.`,
  },
  {
    id: 'only-in-tests',
    applies: path => /^tests\/.+\.test\.(?:[mc]?[jt]s|[jt]sx)$/.test(path),
    test: text => /\.[ \t]*only\b/.test(text),
    cause: 'a committed `.only(`: node and the test runners then skip every other test in the file, and the run still passes.',
    fix: 'remove `.only` before committing; run one test with `--test-name-pattern` instead.',
  },
]

const fileReaderOf = (config, options) => {
  const cache = new Map()
  const baseReader = options?.readFile
    ? options.readFile
    : options?.files
      ? path => (options.files instanceof Map ? options.files.get(path) : options.files[path])
      : config?.[REPO_DIR]
        ? path => { const full = resolve(config[REPO_DIR], path); return existsSync(full) ? readFileSync(full, 'utf8') : undefined }
        : () => undefined
  return path => {
    if (cache.has(path)) return cache.get(path)
    const text = baseReader(path)
    cache.set(path, text)
    return text
  }
}

// The failures for a list of `{ path, line, text }` added lines. When a full file is readable (`options.files`,
// `options.readFile`, or `config`'s repo dir), each line is judged with its file context from line 1; otherwise each
// line is scanned standalone so unit fixtures without files on disk work the same way.
export const checkAdded = (added, config = loadConfig(), list = rules, options = {}) => {
  const readFile = fileReaderOf(config, options)
  const scanned = new Map()
  const codeTextOf = item => {
    if (!scanned.has(item.path)) {
      const full = readFile(item.path)
      scanned.set(item.path, typeof full === 'string' ? codeLinesOf(full) : null)
    }
    const lines = scanned.get(item.path)
    if (lines && item.line >= 1 && item.line <= lines.length) return lines[item.line - 1]
    return codeLinesOf(item.text)[0] ?? ''
  }
  return added.flatMap(item => {
    const active = list.filter(rule => rule.applies(item.path, config, readFile))
    if (!active.length) return []
    const codeText = codeTextOf(item)
    return active
      .filter(rule => rule.test(codeText))
      .map(rule => ({ rule: rule.id, path: item.path, line: item.line, message: `${item.path}:${item.line}: [${rule.id}] ${rule.cause} Fix: ${rule.fix}` }))
  })
}

export const diffAdded = ({ cwd = process.cwd(), base = 'origin/main', head = 'HEAD', run = spawnSync } = {}) => {
  const diff = run('git', ['diff', '--no-ext-diff', '--no-textconv', '--no-color', '--no-renames', '--unified=0', `${base}...${head}`], { cwd, encoding: 'utf8', maxBuffer: 256 * 1024 * 1024 })
  if (diff.error || diff.status !== 0) throw new Error(`code-rules: git could not read ${base}...${head}; fetch the base and run again.`)
  return addedLines(diff.stdout)
}

const headReader = ({ cwd = process.cwd(), head = 'HEAD', run = spawnSync }) => path => {
  const shown = run('git', ['show', `${head}:${path}`], { cwd, encoding: 'utf8', maxBuffer: 256 * 1024 * 1024 })
  return !shown.error && shown.status === 0 ? shown.stdout : undefined
}

export const main = (argv = process.argv.slice(2), { log = console.log, error = console.error } = {}) => {
  const value = name => { const i = argv.indexOf(name); return i === -1 ? undefined : argv[i + 1] }
  try {
    const cwd = resolve(value('--repo-dir') ?? '.')
    const refs = { base: value('--base') ?? 'origin/main', head: value('--head') ?? 'HEAD' }
    const failures = checkAdded(diffAdded({ cwd, ...refs }), loadConfig(cwd, refs), rules, { readFile: headReader({ cwd, head: refs.head }) })
    if (!failures.length) { log('code-rules: PASS, no added line breaks a code rule.'); return 0 }
    for (const failure of failures) error(`FAIL ${failure.message}`)
    error(`code-rules: ${failures.length} FAIL`)
    return 1
  } catch (problem) { error(problem.message); return 1 }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) process.exitCode = main()
